  await capture(page, testInfo, 'modification', '.edit-cover img')
  await page.getByRole('button', { name: 'Enregistrer les modifications' }).click()
  await expect(page.getByRole('heading', { name: 'Atelier modifié', level: 1 })).toBeVisible()
